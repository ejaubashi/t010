import {test,expect} from '@playwright/test';
import {weekdays} from '../src/profile.js';
import {dateKey} from '../src/data.js';

const site='http://localhost:3103';

test('le quattro sezioni salvano dati personali separati e alimentano piano e allenamento',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto(site+'/#profiles');
  await expect(page.getByRole('tab')).toHaveCount(4);
  await page.getByLabel('Peso attuale (kg)',{exact:true}).fill('74.5');
  await page.getByLabel('Peso obiettivo (kg)',{exact:true}).fill('72');
  await page.getByLabel('Altezza (cm)',{exact:true}).fill('178');
  await page.getByRole('button',{name:'Salva sezione'}).click();
  await expect(page.getByText('74,5 kg').first()).toBeVisible();
  await page.getByRole('tab',{name:'Preferenze alimentari',exact:true}).click();
  await page.getByLabel('Allergie e intolleranze',{exact:true}).fill('Nocciole');
  await page.getByLabel('Alimenti da evitare',{exact:true}).fill('broccoli, salmone');
  await page.getByLabel('Alimenti preferiti',{exact:true}).fill('quinoa, ceci');
  await page.getByRole('button',{name:'Salva sezione'}).click();
  await page.getByRole('tab',{name:'Piano alimentare',exact:true}).click();
  await page.getByLabel('Obiettivo giornaliero (kcal)',{exact:true}).fill('2100');
  await page.getByLabel('Proteine (g)',{exact:true}).fill('130');
  await page.getByLabel('Acqua al giorno (litri)',{exact:true}).fill('2.5');
  await page.getByLabel('Indicazioni del piano',{exact:true}).fill('Pranzo dopo le 13:00.');
  await page.getByRole('button',{name:'Salva sezione'}).click();
  await page.getByRole('tab',{name:'Piano di allenamento',exact:true}).click();
  const today=dateKey(new Date()),day=(new Date(today+'T12:00:00Z').getUTCDay()+6)%7;
  await page.getByRole('button',{name:weekdays[day],exact:true}).click();
  await page.getByLabel(`Sessione del ${weekdays[day].toLowerCase()}`,{exact:true}).fill('Forza total body');
  await page.getByLabel(`Durata del ${weekdays[day].toLowerCase()} (min)`,{exact:true}).fill('50');
  await page.getByLabel(`Esercizi del ${weekdays[day].toLowerCase()}`,{exact:true}).fill('Squat · 3 × 10\nRematore · 3 × 12');
  await page.getByRole('button',{name:'Salva sezione'}).click();
  await page.getByRole('button',{name:'Piano alimentare',exact:true}).click();
  await expect(page.getByText('Pranzo dopo le 13:00.')).toBeVisible();
  await expect(page.getByText('Da verificare: Salmone, Broccoli')).toBeVisible();
  await page.getByRole('button',{name:'Aggiungi pasto',exact:true}).click();
  await expect(page.getByRole('dialog').getByText(/Nocciole/)).toBeVisible();
  await page.getByRole('button',{name:'Chiudi finestra'}).click();
  await page.getByRole('button',{name:'Allenamento',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Forza total body'})).toBeVisible();
  await expect(page.getByText('Squat · 3 × 10',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Segna allenamento completato'}).click();
  await expect(page.getByRole('button',{name:'Completato · Annulla'})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button',{name:'Completato · Annulla'})).toBeVisible();
  await page.getByRole('button',{name:'Profilo Giulia',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Nessun programma impostato'})).toBeVisible();
  await page.getByRole('button',{name:'Profili',exact:true}).click();
  await expect(page.getByLabel('Peso attuale (kg)',{exact:true})).toHaveValue('');
  await page.getByRole('button',{name:'Profilo Endi',exact:true}).click();
  await expect(page.getByLabel('Peso attuale (kg)',{exact:true})).toHaveValue('74.5');
  const s=await page.evaluate(()=>JSON.parse(localStorage.getItem('tavola-household-v1')));
  expect(s.profiles.me.weightHistory).toHaveLength(1);
  expect(s.profiles.me.food.preferred).toBe('quinoa, ceci');
  expect(s.profiles.me.nutrition.protein).toBe(130);
  expect(s.profiles.her.target).toBe(1800);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
});

test('la panoramica riepiloga e il piano è l’unica pagina di gestione dei pasti',async({page})=>{
  await page.goto(site);
  await expect(page.getByRole('heading',{name:'Il prossimo pasto'})).toBeVisible();
  await expect(page.locator('.week-picker')).toHaveCount(0);
  await expect(page.locator('.meal-row')).toHaveCount(0);
  await page.getByRole('button',{name:'Piano alimentare',exact:true}).click();
  await expect(page.locator('.week-picker')).toHaveCount(1);
  await expect(page.locator('.meal-row')).toHaveCount(4);
  await page.getByRole('button',{name:'Profili',exact:true}).click();
  await page.getByLabel('Peso attuale (kg)',{exact:true}).fill('-5');
  await page.getByRole('button',{name:'Salva sezione'}).click();
  expect(await page.getByLabel('Peso attuale (kg)',{exact:true}).evaluate(el=>el.validity.valid)).toBe(false);
});
